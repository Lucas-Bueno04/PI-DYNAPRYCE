"""Porta p_sess e repositórios de auth (fora da RLS por inquilino)."""

from collections.abc import Sequence
from datetime import datetime
from typing import Protocol
from uuid import UUID

from dynaprice.dominio.modelos.autenticacao import Papel, RegistroDeRefresh, Usuario


class RepositorioDeUsuarios(Protocol):
    def obter(self, usuario_id: UUID) -> Usuario | None: ...

    def obter_travado(self, usuario_id: UUID) -> Usuario | None:
        """Lê com trava: a sessão só abre sobre a credencial que acabou de ser conferida."""
        ...

    def obter_por_email(self, email: str) -> Usuario | None: ...

    def criar(self, usuario: Usuario) -> None: ...

    # Escritas pontuais: um login em andamento nunca regrava senha, TOTP ou `ativo` (achado A4).
    def registrar_falha_login(self, usuario_id: UUID) -> int: ...

    def bloquear(self, usuario_id: UUID, ate: datetime) -> None: ...

    def zerar_falhas(self, usuario_id: UUID) -> None: ...

    def trocar_hash_se_igual(self, usuario_id: UUID, antigo: str, novo: str) -> None: ...

    def registrar_passo_totp(self, usuario_id: UUID, passo: int) -> bool:
        """False se o passo não é posterior ao último aceito (reuso, RFC 6238 §5.2)."""
        ...

    def iniciar_cadastro_mfa(self, usuario_id: UUID, totp_cifrado: bytes) -> None: ...

    def ativar_mfa(self, usuario_id: UUID, passo: int, totp_verificado: bytes) -> bool:
        """False se o MFA já estava ativo ou o segredo mudou depois de verificado."""
        ...

    def desligar_mfa(self, usuario_id: UUID) -> None: ...

    def desativar(self, usuario_id: UUID) -> None: ...

    def redefinir_senha(self, usuario_id: UUID, senha_hash: str) -> None: ...

    def papeis(self, usuario_id: UUID, tenant_id: UUID) -> frozenset[Papel]: ...

    def inquilinos(self, usuario_id: UUID) -> Sequence[UUID]: ...

    def definir_papeis(
        self, usuario_id: UUID, tenant_id: UUID, papeis: frozenset[Papel]
    ) -> None: ...

    def listar_do_inquilino(self, tenant_id: UUID) -> Sequence[Usuario]: ...

    def existe_administrador(self) -> bool: ...

    def criar_inquilino(self, tenant_id: UUID, nome: str) -> None: ...

    def inquilinos_ativos(self) -> Sequence[UUID]: ...

    def com_totp(self) -> Sequence[tuple[UUID, bytes]]: ...

    def trocar_totp(self, usuario_id: UUID, totp_cifrado: bytes) -> None: ...


class RepositorioDeSessoes(Protocol):
    def criar_familia(
        self,
        usuario_id: UUID,
        tenant_id: UUID,
        mfa_verificado: bool,
        agora: datetime,
        expira_em: datetime,
    ) -> UUID: ...

    def registrar_token(
        self, hash_sha256: bytes, familia_id: UUID, agora: datetime, expira_em: datetime
    ) -> None: ...

    def travar_token(self, hash_sha256: bytes) -> RegistroDeRefresh | None: ...

    def marcar_usado(self, hash_sha256: bytes, familia_id: UUID, agora: datetime) -> None: ...

    def revogar_familia(self, familia_id: UUID, agora: datetime, motivo: str) -> None: ...

    def revogar_do_usuario(self, usuario_id: UUID, agora: datetime, motivo: str) -> None: ...

    def revogar_no_inquilino(
        self, usuario_id: UUID, tenant_id: UUID, agora: datetime, motivo: str
    ) -> None: ...


class RepositorioDeRecuperacao(Protocol):
    def substituir_codigos(self, usuario_id: UUID, codigos: Sequence[tuple[UUID, str]]) -> None: ...

    def hash_do_codigo(self, usuario_id: UUID, codigo_id: UUID) -> str | None:
        """Hash do código ainda não usado; custo fixo de uma verificação (achado A3)."""
        ...

    def consumir_codigo(self, codigo_id: UUID, agora: datetime) -> bool: ...

    def invalidar_redefinicoes(self, usuario_id: UUID) -> None: ...

    def criar_redefinicao(
        self, hash_sha256: bytes, usuario_id: UUID, expira_em: datetime
    ) -> None: ...

    def consumir_redefinicao(self, hash_sha256: bytes, agora: datetime) -> UUID | None:
        """Marca o link como usado e devolve o usuário; None se inválido, usado ou vencido."""
        ...


class LimiteDeTentativas(Protocol):
    def bloqueado_ate(self, ip_hash: bytes) -> datetime | None: ...

    def registrar_falha(self, ip_hash: bytes, agora: datetime, desde: datetime) -> int:
        """Soma uma falha e devolve o total; falhas anteriores a `desde` já não contam."""
        ...

    def bloquear(self, ip_hash: bytes, ate: datetime) -> None: ...
